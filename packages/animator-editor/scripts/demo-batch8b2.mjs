// Batch 8b-2 screenshots: rig event definitions, the Animate event panel, the key inspector payload, the keyboard shortcuts editor (sandbox server, never 5211).
//   node packages/animator-editor/scripts/demo-batch8b2.mjs [outDir]
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { revealTabs } from "./tab-reveal.mjs";
import { demoServer } from "./demo-server.mjs";

const here = fileURLToPath(new URL(".", import.meta.url));
const require = createRequire(resolve(here, "../../animator/package.json"));
const { chromium } = require("@playwright/test");
const out = resolve(process.argv[2] ?? resolve(here, "../../../test-results/batch-shots/b8"));
mkdirSync(out, { recursive: true });
const { url } = await demoServer();
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = revealTabs(await (await browser.newContext({ viewport: { width: 1680, height: 1000 } })).newPage(), { workspace: null });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e.stack ?? e)));
await page.goto(url);
await page.waitForFunction(() => !!window.atlasEditor, null, { timeout: 60_000 });
await page.waitForTimeout(1500);
const E = (fn, arg) => page.evaluate(fn, arg);
const shot = async (name) => {
  await page.waitForTimeout(600);
  await page.screenshot({ path: resolve(out, name) });
  console.log(name);
};
await E(() => window.atlasEditor.mountOutfit("pro-turned"));
await page.waitForTimeout(1500);
await E(() => window.atlasEditor.workspace("rig"));
await E(() => window.atlasEditor.showTab("rig"));
await page.waitForTimeout(500);
await page.click('.ol-row[data-id="g:events"]');
await page.fill("#setup-event-name", "footstep");
await page.click("#setup-event-add");
await page.waitForTimeout(900);
await page.fill('[data-field="footstep.int"]', "2");
await page.fill('[data-field="footstep.audio"]', "step_soft");
await page.keyboard.press("Tab");
await shot("b8c-01-rig-events.png");
await E(() => window.atlasEditor.workspace("pro"));
await page.click("#newclip-open");
await page.fill("#newclip-name", "demo_events");
await page.click("#newclip-make");
await page.waitForTimeout(500);
await E(() => { window.atlasEditor.workspace("animate"); window.atlasEditor.showTab("keys"); window.atlasEditor.setTime(3 / 30); });
await page.waitForTimeout(500);
await page.selectOption("#eventpanel select", "footstep");
await page.fill("#event-payload-int", "2");
await page.click("#eventpanel >> text=Add at playhead");
await page.waitForTimeout(500);
await E(() => window.atlasEditor.selectKeys?.([{ row: "event", time: 3 / 30 }]));
await shot("b8c-02-animate-events.png");
await page.click("#helpbtn");
await page.click("#help-keymap");
await page.fill("#keymap-search", "key");
await shot("b8c-03-keymap-editor.png");
await page.click('[data-rebind="key"]');
await page.keyboard.press("r");
await shot("b8c-04-keymap-conflict.png");
await page.click('[data-cancel="key"]');
console.log("page errors:", errors.length, errors[0] ?? "");
await browser.close();
process.exit(errors.length ? 1 : 0);
